// Template library tooling.
//
// Bundled templates are plain JSON files in src/templates/library/<format>/.
// This script:
//   1. (with --author) compiles the authoring kit in src/templates/authoring/
//      and writes the templates it defines as JSON files into the library;
//   2. always regenerates src/templates/library/index.ts (the lazily loaded
//      module that imports every JSON file) and src/templates/catalog.generated.json
//      (light metadata the app can use before the library has loaded).
//
// Adding a template = dropping a JSON file into the library and running
// `npm run templates` (dev and build run step 2 automatically).
import { build } from 'esbuild';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const libraryDir = path.join(root, 'src/templates/library');
const author = process.argv.includes('--author');

async function authorTemplates() {
  const tmp = path.join(root, 'node_modules/.cache/stardeck-templates');
  await mkdir(tmp, { recursive: true });
  const outfile = path.join(tmp, 'authoring.mjs');
  await build({
    entryPoints: [path.join(root, 'src/templates/authoring/index.ts')],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    tsconfig: path.join(root, 'tsconfig.json'),
    logLevel: 'warning',
    // Authoring runs in Node; there is no DOM or canvas here.
    define: { 'process.env.NODE_ENV': '"production"' },
  });
  const { buildAuthoredTemplates, authoringWarnings } = await import(`${pathToFileURL(outfile).href}?t=${Date.now()}`);
  const templates = buildAuthoredTemplates();
  for (const warning of authoringWarnings) console.warn(`templates: ${warning}`);
  for (const t of templates) {
    const dir = path.join(libraryDir, t.format);
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(dir, `${t.id}.json`), `${JSON.stringify(t, null, 2)}\n`);
  }
  await rm(outfile, { force: true });
  console.log(`templates: authored ${templates.length} template(s)`);
}

async function listLibrary() {
  const files = [];
  for (const format of (await readdir(libraryDir, { withFileTypes: true })).filter((d) => d.isDirectory())) {
    for (const file of await readdir(path.join(libraryDir, format.name))) {
      if (file.endsWith('.json')) files.push(`${format.name}/${file}`);
    }
  }
  return files.sort();
}

const isPhotoSlot = (el) => el.type === 'image' && !el.assetId && !el.hidden;

async function writeIndex() {
  const files = await listLibrary();
  const catalog = [];
  const ids = new Set();
  for (const file of files) {
    const t = JSON.parse(await readFile(path.join(libraryDir, file), 'utf8'));
    if (ids.has(t.id)) throw new Error(`Duplicate template id "${t.id}" (${file})`);
    ids.add(t.id);
    catalog.push({
      id: t.id,
      name: t.name,
      format: t.format,
      sizeId: t.sizeId,
      style: t.style ?? 'editorial',
      description: t.description,
      tags: t.tags,
      palette: t.palette,
      width: t.doc.slideWidth,
      height: t.doc.slideHeight,
      slides: t.doc.slides.length,
      photoSlots: t.doc.elements.filter(isPhotoSlot).length,
    });
  }
  const names = files.map((_, i) => `t${i}`);
  const index = [
    '// Generated by scripts/build-templates.mjs from the JSON files in this folder — do not edit.',
    '// Loaded lazily (see ../registry.ts) so the template library stays out of the main bundle.',
    ...files.map((file, i) => `import ${names[i]} from './${file}';`),
    '',
    `export const LIBRARY: unknown[] = [${names.join(', ')}];`,
    '',
  ].join('\n');
  await writeFile(path.join(libraryDir, 'index.ts'), index);
  await writeFile(path.join(root, 'src/templates/catalog.generated.json'), `${JSON.stringify(catalog, null, 2)}\n`);
  console.log(`templates: indexed ${files.length} template(s)`);
}

if (author) await authorTemplates();
await writeIndex();
